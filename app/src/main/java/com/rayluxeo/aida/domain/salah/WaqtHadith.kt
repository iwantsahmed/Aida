    /**
     * Returns the full list of authentic Hadiths for [prayer].
     */
    fun allForPrayer(prayer: Prayer): List<WaqtHadith> = when (prayer) {
        Prayer.FAJR -> FAJR_HADITHS
        Prayer.DHUHR -> DHUHR_HADITHS
        Prayer.ASR -> ASR_HADITHS
        Prayer.MAGHRIB -> MAGHRIB_HADITHS
        Prayer.ISHA -> ISHA_HADITHS
        Prayer.TAHAJJUD -> TAHAJJUD_HADITHS
    }

    /**
     * Resolves the Hadith for a given [prayer] on [date].
     *
     * Uses [date.toEpochDay] with [offset] so each waqt and each day smoothly rotates to a new
     * non-repeating Hadith without wrapping on yearly boundaries.
     */
    fun forPrayer(prayer: Prayer, date: LocalDate = LocalDate.now(), offset: Int = 0): WaqtHadith {
        val list = allForPrayer(prayer)
        val epochDay = date.toEpochDay()
        val index = Math.floorMod(epochDay + offset, list.size.toLong()).toInt()
        return list[index]
    }
